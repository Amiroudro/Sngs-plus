/// "2026-11-08" -> "রবিবার, ৮ নভেম্বর ২০২৬" (bn) / "Sunday, 8 November
/// 2026" (en). Weekday is derived from the date itself, never invented:
/// 8 November 2026 is a Sunday (7 November 2026 is the Saturday).
String formatEditionDateLong(String isoDate, String lang) {
  final dt = DateTime.tryParse(isoDate);
  if (dt == null) return formatEditionDate(isoDate, lang);
  final weekdays = lang == 'en' ? weekdaysEn : weekdaysBn;
  return '${weekdays[dt.weekday] ?? ''}, ${formatEditionDate(isoDate, lang)}';
}

/// Latin digits 0–9 -> Bangla digits ০–৯. Presentation only: the
/// underlying data keeps its original digits; the story screen renders
/// Bangla digits in Bengali text (mockup image-6: "৭ নভেম্বর ২০২৬",
/// "৩ / ১৪", "১,৩৫০ কোটি টাকা"). Non-digits pass through untouched.
String toBnDigits(String text) {
  const digits = '০১২৩৪৫৬৭৮৯';
  final out = StringBuffer();
  for (var i = 0; i < text.length; i++) {
    final c = text[i];
    final code = c.codeUnitAt(0);
    if (code >= 0x30 && code <= 0x39) {
      out.write(digits[code - 0x30]);
    } else {
      out.write(c);
    }
  }
  return out.toString();
}

/// Renders [text] for the story screen: Bangla digits when the UI
/// language is Bengali, unchanged otherwise.
String storyDigits(String text, String lang) =>
    lang == 'bn' ? toBnDigits(text) : text;
