/// "2026-11-07" -> "৭ নভেম্বর ২০২৬" (bn) / "7 November 2026" (en).
/// Day and year are Bangla digits in Bengali mode (Phase 4), so every
/// call site renders authentic Bengali dates without its own conversion.
String formatEditionDate(String isoDate, String lang) {
  final parts = isoDate.split('-');
  if (parts.length != 3) return isoDate;
  final year = parts[0];
  final month = int.tryParse(parts[1]) ?? 0;
  final day = int.tryParse(parts[2]) ?? 0;
  final months = lang == 'en' ? monthsEn : monthsBn;
  final monthName = months[month];
  if (monthName == null || day == 0) return isoDate;
  if (lang == 'en') return '$day $monthName $year';
  return '${toBnDigits(day.toString())} $monthName '
      '${toBnDigits(year)}';
}

